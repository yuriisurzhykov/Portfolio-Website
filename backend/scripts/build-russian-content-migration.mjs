// Rebuild the reviewed data migration without any network or model calls.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const directory = path.join(root, "content-translations/ru");
const packs = readdirSync(directory).filter((name) => name.endsWith(".json")).sort().map((name) => JSON.parse(readFileSync(path.join(directory, name), "utf8")));
if (packs.length !== 12) throw new Error("Expected twelve reviewed translations");
const payload = JSON.stringify(packs);
if (payload.includes("$translations$") || payload.includes("$backfill$")) throw new Error("SQL delimiter in content");
const sql = `-- Generated by backend/scripts/build-russian-content-migration.mjs.
-- Source: public English content captured 2026-11-11 from https://yuriisoft.me.
-- Only matching published records without translations or pending drafts qualify.
-- Skipped content is logged; no English document, URL or publication date changes.
BEGIN;
DO $backfill$
DECLARE
    pack jsonb;
    row_data jsonb;
    current_source jsonb;
    current_blocks jsonb;
    metadata_keys text[];
    field_name text;
    table_name text;
    document_column text;
    russian_column text;
    translated_document text;
    assignments text;
BEGIN
    FOR pack IN SELECT value FROM jsonb_array_elements($translations$${payload}$translations$::jsonb)
    LOOP
        table_name := CASE pack->>'kind' WHEN 'post' THEN 'Post' ELSE 'Work' END;
        document_column := CASE pack->>'kind' WHEN 'post' THEN 'bodyDocumentId' ELSE 'caseStudyDocumentId' END;
        russian_column := document_column || 'Ru';
        metadata_keys := CASE pack->>'kind' WHEN 'post' THEN ARRAY['title','category','excerpt'] ELSE ARRAY['title','summary','role','startedLabel','shippedLabel'] END;

        EXECUTE format('SELECT to_jsonb(t) FROM %I t WHERE slug = $1 FOR UPDATE', table_name)
            INTO row_data USING pack->>'slug';
        IF row_data IS NULL THEN CONTINUE; END IF;
        IF row_data->>'lifecycleState' <> 'PUBLISHED'
            OR (pack->>'kind' = 'post' AND row_data->>'status' <> 'published')
            OR row_data->>document_column IS NULL
            OR row_data->>russian_column IS NOT NULL
            OR EXISTS (SELECT 1 FROM "ContentDraft" WHERE kind = pack->>'kind' AND "entityId" = row_data->>'id')
        THEN
            RAISE NOTICE 'Russian backfill skipped existing translation/draft/non-public record: %', pack->>'slug';
            CONTINUE;
        END IF;

        current_source := '{}'::jsonb;
        FOREACH field_name IN ARRAY metadata_keys LOOP
            current_source := current_source || jsonb_build_object(field_name, row_data->field_name->>'en');
        END LOOP;
        SELECT coalesce(jsonb_agg(jsonb_strip_nulls(jsonb_build_object('type', type, 'text', text, 'data', data)) ORDER BY "order"), '[]'::jsonb)
            INTO current_blocks FROM "Block" WHERE "documentId" = row_data->>document_column;
        current_source := current_source || jsonb_build_object('blocks', current_blocks);
        IF current_source <> jsonb_strip_nulls(pack->'source')
            OR EXISTS (SELECT 1 FROM unnest(metadata_keys) AS f WHERE btrim(coalesce(row_data->f->>'ru', '')) <> '')
        THEN
            RAISE NOTICE 'Russian backfill skipped edited source/metadata: %', pack->>'slug';
            CONTINUE;
        END IF;

        translated_document := 'ru-20261112-' || md5((pack->>'kind') || ':' || (pack->>'slug'));
        INSERT INTO "Document" (id, "createdAt", "updatedAt") VALUES (translated_document, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);
        INSERT INTO "Block" (id, "documentId", "order", type, text, data)
            SELECT translated_document || '-' || ordinal, translated_document, ordinal - 1, block->>'type', block->'text', block->'data'
            FROM jsonb_array_elements(pack->'translation'->'blocks') WITH ORDINALITY AS blocks(block, ordinal);

        assignments := '';
        FOREACH field_name IN ARRAY metadata_keys LOOP
            assignments := assignments || format('%I = jsonb_set(%I, ''{ru}'', $1->%L), ', field_name, field_name, field_name);
        END LOOP;
        EXECUTE format('UPDATE %I SET %s %I = $2, "contentUpdatedAt" = CURRENT_TIMESTAMP, "updatedAt" = CURRENT_TIMESTAMP WHERE id = $3', table_name, assignments, russian_column)
            USING pack->'translation', translated_document, row_data->>'id';
        RAISE NOTICE 'Russian backfill translated: %', pack->>'slug';
    END LOOP;
END;
$backfill$;
COMMIT;
`;
const target = path.join(root, "prisma/migrations/20261112000000_backfill_russian_content/migration.sql");
if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== sql) throw new Error("Russian migration differs from reviewed translation packs");
} else {
    writeFileSync(target, sql);
}
